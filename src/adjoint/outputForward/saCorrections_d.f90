          temp10 = uux*uux + uuy*uuy + uuz*uuz + vvx*vvx + vvy*vvy + vvz&
&           *vvz + wwx*wwx + wwy*wwy + wwz*wwz
          gradu2d = temp10*2*fact*factd + fact**2*(2*uux*uuxd+2*uuy*uuyd&
&           +2*uuz*uuzd+2*vvx*vvxd+2*vvy*vvyd+2*vvz*vvzd+2*wwx*wwxd+2*&
&           wwy*wwyd+2*wwz*wwzd)
          gradu2 = fact*fact*temp10
! inverse of the local speed of sound squared.
          temp10 = gamma(i, j, k)*p(i, j, k)
          temp9 = w(i, j, k, irho)/temp10
          a2invd = (wd(i, j, k, irho)-temp9*gamma(i, j, k)*pd(i, j, k))/&
&           temp10
          a2inv = temp9
          compcoefd = sac5*(gradu2*a2invd+a2inv*gradu2d)
          compcoef = sac5*a2inv*gradu2
          temp10 = w(i, j, k, itu1)
          scratchd(i, j, k, idvt) = scratchd(i, j, k, idvt) - temp10**2*&
&           compcoefd - compcoef*2*temp10*wd(i, j, k, itu1)
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) - compcoef*(&
&           temp10*temp10)
        end do
      end do
    end do
  end subroutine sacompressibilitysource_d

  subroutine sacompressibilitysource()
!
!  compressibility correction of spalart (aiaa 2000-2306).
!  the term -c5 nutilde^2/a^2 (du_i/dx_j)(du_i/dx_j) is added to
!  the source term stored in scratch(:,:,:,idvt) by sasource or
!  saedwardssource, and its (positive) contribution to
!  -dsource/dnutilde is added to qq.
    use blockpointers
    use constants
    use inputphysics, only : sac5
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz
    real(kind=realtype) :: fact, gradu2, a2inv, compcoef
    do k=2,kl
      do j=2,jl
        do i=2,il
! velocity gradients in the cell center, scaled by
! 2*vol. see sasource in sa.f90.
          uux = w(i+1, j, k, ivx)*si(i, j, k, 1) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivx)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 1) + w(i, j, k+1, ivx)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 1)
          uuy = w(i+1, j, k, ivx)*si(i, j, k, 2) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivx)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 2) + w(i, j, k+1, ivx)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 2)
          uuz = w(i+1, j, k, ivx)*si(i, j, k, 3) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivx)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 3) + w(i, j, k+1, ivx)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 3)
          vvx = w(i+1, j, k, ivy)*si(i, j, k, 1) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivy)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 1) + w(i, j, k+1, ivy)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 1)
          vvy = w(i+1, j, k, ivy)*si(i, j, k, 2) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivy)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 2) + w(i, j, k+1, ivy)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 2)
          vvz = w(i+1, j, k, ivy)*si(i, j, k, 3) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivy)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 3) + w(i, j, k+1, ivy)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 3)
          wwx = w(i+1, j, k, ivz)*si(i, j, k, 1) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivz)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 1) + w(i, j, k+1, ivz)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 1)
          wwy = w(i+1, j, k, ivz)*si(i, j, k, 2) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivz)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 2) + w(i, j, k+1, ivz)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 2)
          wwz = w(i+1, j, k, ivz)*si(i, j, k, 3) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivz)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 3) + w(i, j, k+1, ivz)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 3)
! (du_i/dx_j)(du_i/dx_j); the gradients above are
! scaled by 2*vol.
          fact = half/vol(i, j, k)
          gradu2 = fact**2*(uux**2+uuy**2+uuz**2+vvx**2+vvy**2+vvz**2+&
&           wwx**2+wwy**2+wwz**2)
! inverse of the local speed of sound squared.
          a2inv = w(i, j, k, irho)/(gamma(i, j, k)*p(i, j, k))
          compcoef = sac5*a2inv*gradu2
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) - compcoef*w(i&
&           , j, k, itu1)**2
        end do
      end do
    end do
  end subroutine sacompressibilitysource

