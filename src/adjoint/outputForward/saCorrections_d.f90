!
!      the following term is added to the right hand side of the
!      (non-conservative) nutilde equation,
!
!        -c5 * nutilde^2 / a^2 * (du_i/dx_j) (du_i/dx_j),   c5 = 3.5,
!
!      where a is the local speed of sound.
!
