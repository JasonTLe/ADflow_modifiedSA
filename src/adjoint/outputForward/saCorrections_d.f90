          rr = tanhx*tanhoneinv
          ggd = (rsacw2*(6*rr**5-1.0)+1.0)*rrd
          gg = rr + rsacw2*(rr**6-rr)
          gg6d = 6*gg**5*ggd
          gg6 = gg**6
