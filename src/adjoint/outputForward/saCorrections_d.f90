          destd = rsacw1*(temp10**2*(dist2inv*fwsad+fwsa*dist2invd)+fwsa&
&           *dist2inv*2*temp10*wd(i, j, k, itu1))
          dest = rsacw1*(fwsa*dist2inv*(temp10*temp10))
          scratchd(i, j, k, idvt) = prodd - destd
          scratch(i, j, k, idvt) = prod - dest
        end do
      end do
    end do
