!  source terms of the edwards-chandra sa model.
!  determine the source term and its derivative w.r.t. nutilde
!  for all internal cells of the block.
!  remember that the sa field variable nutilde = w(i,j,k,itu1)
    use blockpointers
    use constants
    use paramturb
    use inputdiscretization, only : approxsa
    implicit none
! local parameters
    real(kind=realtype), parameter :: f23=two*third
    real(kind=realtype), parameter :: xminn=1.e-10_realtype
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: cv13, kar2inv, cw36, tanhoneinv
    real(kind=realtype) :: fv1, nufv, ss, nu, dist2inv, chi, chi2, chi3
    real(kind=realtype) :: xx, tanhx, rr, gg, gg6, termfw, fwsa
    real(kind=realtype) :: prod, dest
    real(kind=realtype) :: dfv1, dnufv, dxx, drr, dgg, dfw
    real(kind=realtype) :: uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz
    real(kind=realtype) :: div2, fact, sxx, syy, szz, sxy, sxz, syz
    real(kind=realtype) :: strainmag2, strainprod
    intrinsic tanh
    intrinsic max
    intrinsic sqrt
    real(kind=realtype) :: max1
! set model constants
    cv13 = rsacv1**3
    kar2inv = one/rsak**2
    cw36 = rsacw3**6
    tanhoneinv = one/tanh(one)
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the velocity gradients in the cell center,
! scaled by 2*vol. see sasource in sa.f90.
          uux = w(i+1, j, k, ivx)*si(i, j, k, 1) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivx)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 1) + w(i, j, k+1, ivx)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 1)
          uuy = w(i+1, j, k, ivx)*si(i, j, k, 2) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivx)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 2) + w(i, j, k+1, ivx)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 2)
          uuz = w(i+1, j, k, ivx)*si(i, j, k, 3) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivx)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 3) + w(i, j, k+1, ivx)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 3)
          vvx = w(i+1, j, k, ivy)*si(i, j, k, 1) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivy)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 1) + w(i, j, k+1, ivy)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 1)
          vvy = w(i+1, j, k, ivy)*si(i, j, k, 2) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivy)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 2) + w(i, j, k+1, ivy)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 2)
          vvz = w(i+1, j, k, ivy)*si(i, j, k, 3) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivy)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 3) + w(i, j, k+1, ivy)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 3)
          wwx = w(i+1, j, k, ivz)*si(i, j, k, 1) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivz)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 1) + w(i, j, k+1, ivz)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 1)
          wwy = w(i+1, j, k, ivz)*si(i, j, k, 2) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivz)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 2) + w(i, j, k+1, ivz)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 2)
          wwz = w(i+1, j, k, ivz)*si(i, j, k, 3) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivz)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 3) + w(i, j, k+1, ivz)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 3)
! strain rate tensor; the factor 1/(4*vol) accounts for
! the 2*vol scaling of the gradients.
          fact = fourth/vol(i, j, k)
          sxx = two*fact*uux
          syy = two*fact*vvy
          szz = two*fact*wwz
          sxy = fact*(uuy+vvx)
          sxz = fact*(uuz+wwx)
          syz = fact*(vvz+wwy)
          div2 = f23*(sxx+syy+szz)**2
          strainmag2 = two*(sxy**2+sxz**2+syz**2) + sxx**2 + syy**2 + &
&           szz**2
! s = 2 s_ij s_ij - 2/3 (div u)^2. edwards uses sqrt(s).
! limit it from below (like sst in sa.f90), which also
! keeps the derivative of the square root finite.
          strainprod = two*strainmag2 - div2
          if (strainprod .lt. xminn**2) then
            max1 = xminn**2
          else
            max1 = strainprod
          end if
          ss = sqrt(max1)
! laminar kinematic viscosity, inverse wall distance
! squared, chi and fv1.
          nu = rlv(i, j, k)/w(i, j, k, irho)
          dist2inv = one/d2wall(i, j, k)**2
          chi = w(i, j, k, itu1)/nu
          chi2 = chi*chi
          chi3 = chi*chi2
          fv1 = chi3/(chi3+cv13)
! nufv = nu + nutilde*fv1, such that
! stilde * nutilde = ss * nufv.
          nufv = nu + w(i, j, k, itu1)*fv1
          if (nufv .lt. xminn*nu) then
            nufv = xminn*nu
          else
            nufv = nufv
          end if
! r = tanh(nutilde / (stilde kappa^2 d^2)) / tanh(1)
!   = tanh(nutilde^2 / (ss nufv kappa^2 d^2)) / tanh(1).
! no cut-off is needed since r <= 1/tanh(1).
          xx = w(i, j, k, itu1)**2*kar2inv*dist2inv/(ss*nufv)
          tanhx = tanh(xx)
          rr = tanhx*tanhoneinv
          gg = rr + rsacw2*(rr**6-rr)
          gg6 = gg**6
          termfw = ((one+cw36)/(gg6+cw36))**sixth
          fwsa = gg*termfw
! production cb1*stilde*nutilde and destruction.
          if (approxsa) then
            prod = zero
          else
            prod = rsacb1*ss*nufv
          end if
          dest = rsacw1*fwsa*dist2inv*w(i, j, k, itu1)**2
          scratch(i, j, k, idvt) = prod - dest
        end do
      end do
    end do
  end subroutine saedwardssource

