&           temp8*wd(i-1, j, k, ivz) - temp7*sid(i-1, j, k, 3) + temp6*&
&           wd(i, j+1, k, ivz) + temp5*sjd(i, j, k, 3) + temp4*wd(i, j, &
&           k+1, ivz) + temp3*skd(i, j, k, 3) - temp2*wd(i, j-1, k, ivz)&
&           - temp1*sjd(i, j-1, k, 3) - temp0*wd(i, j, k-1, ivz) - temp*&
&           skd(i, j, k-1, 3)
          wwz = temp9*temp10 - temp7*temp8 + temp5*temp6 + temp3*temp4 -&
&           temp1*temp2 - temp*temp0
! (du_i/dx_j)(du_i/dx_j); the gradients above are
! scaled by 2*vol.
          temp10 = half/vol(i, j, k)
          factd = -(temp10*vold(i, j, k)/vol(i, j, k))
          fact = temp10
          temp10 = uux*uux + uuy*uuy + uuz*uuz + vvx*vvx + vvy*vvy + vvz&
&           *vvz + wwx*wwx + wwy*wwy + wwz*wwz
          gradu2d = temp10*2*fact*factd + fact**2*(2*uux*uuxd+2*uuy*uuyd&
&           +2*uuz*uuzd+2*vvx*vvxd+2*vvy*vvyd+2*vvz*vvzd+2*wwx*wwxd+2*&
&           wwy*wwyd+2*wwz*wwzd)
          gradu2 = fact*fact*temp10
! inverse of the local speed of sound squared.
          temp10 = gamma(i, j, k)*p(i, j, k)
          temp9 = w(i, j, k, irho)/temp10
          a2invd = (wd(i, j, k, irho)-temp9*gamma(i, j, k)*pd(i, j, k))/&
&           temp10
          a2inv = temp9
          compcoefd = sac5*(gradu2*a2invd+a2inv*gradu2d)
          compcoef = sac5*a2inv*gradu2
          temp10 = w(i, j, k, itu1)
          scratchd(i, j, k, idvt) = scratchd(i, j, k, idvt) - temp10**2*&
&           compcoefd - compcoef*2*temp10*wd(i, j, k, itu1)
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) - compcoef*(&
&           temp10*temp10)
        end do
      end do
    end do
  end subroutine sacompressibilitysource_d

  subroutine sacompressibilitysource()
!
!  compressibility correction of spalart (aiaa 2000-2306).
!  the term -c5 nutilde^2/a^2 (du_i/dx_j)(du_i/dx_j) is added to
!  the source term stored in scratch(:,:,:,idvt) by sasource or
!  saedwardssource, and its (positive) contribution to
!  -dsource/dnutilde is added to qq.
    use blockpointers
    use constants
    use inputphysics, only : sac5
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: uux, uuy, uuz, vvx, vvy, vvz, wwx, wwy, wwz
    real(kind=realtype) :: fact, gradu2, a2inv, compcoef
    do k=2,kl
      do j=2,jl
        do i=2,il
! velocity gradients in the cell center, scaled by
! 2*vol. see sasource in sa.f90.
          uux = w(i+1, j, k, ivx)*si(i, j, k, 1) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivx)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 1) + w(i, j, k+1, ivx)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 1)
          uuy = w(i+1, j, k, ivx)*si(i, j, k, 2) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivx)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 2) + w(i, j, k+1, ivx)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 2)
          uuz = w(i+1, j, k, ivx)*si(i, j, k, 3) - w(i-1, j, k, ivx)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivx)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivx)*sj(i, j-1, k, 3) + w(i, j, k+1, ivx)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivx)*sk(i, j, k-1, 3)
          vvx = w(i+1, j, k, ivy)*si(i, j, k, 1) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivy)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 1) + w(i, j, k+1, ivy)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 1)
          vvy = w(i+1, j, k, ivy)*si(i, j, k, 2) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivy)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 2) + w(i, j, k+1, ivy)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 2)
          vvz = w(i+1, j, k, ivy)*si(i, j, k, 3) - w(i-1, j, k, ivy)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivy)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivy)*sj(i, j-1, k, 3) + w(i, j, k+1, ivy)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivy)*sk(i, j, k-1, 3)
          wwx = w(i+1, j, k, ivz)*si(i, j, k, 1) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 1) + w(i, j+1, k, ivz)*sj(i, j, k, 1) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 1) + w(i, j, k+1, ivz)*sk(i, j, k, 1&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 1)
          wwy = w(i+1, j, k, ivz)*si(i, j, k, 2) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 2) + w(i, j+1, k, ivz)*sj(i, j, k, 2) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 2) + w(i, j, k+1, ivz)*sk(i, j, k, 2&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 2)
          wwz = w(i+1, j, k, ivz)*si(i, j, k, 3) - w(i-1, j, k, ivz)*si(&
&           i-1, j, k, 3) + w(i, j+1, k, ivz)*sj(i, j, k, 3) - w(i, j-1&
&           , k, ivz)*sj(i, j-1, k, 3) + w(i, j, k+1, ivz)*sk(i, j, k, 3&
&           ) - w(i, j, k-1, ivz)*sk(i, j, k-1, 3)
! (du_i/dx_j)(du_i/dx_j); the gradients above are
! scaled by 2*vol.
          fact = half/vol(i, j, k)
          gradu2 = fact**2*(uux**2+uuy**2+uuz**2+vvx**2+vvy**2+vvz**2+&
&           wwx**2+wwy**2+wwz**2)
! inverse of the local speed of sound squared.
          a2inv = w(i, j, k, irho)/(gamma(i, j, k)*p(i, j, k))
          compcoef = sac5*a2inv*gradu2
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) - compcoef*w(i&
&           , j, k, itu1)**2
        end do
      end do
    end do
  end subroutine sacompressibilitysource

!  differentiation of sacatrisviscous in forward (tangent) mode (with options i4 dr8 r8):
!   variations   of useful results: *scratch
!   with respect to varying inputs: *w *rlv *scratch *vol *si *sj
!                *sk
!   rw status of diff variables: *w:in *rlv:in *scratch:in-out
!                *vol:in *si:in *sj:in *sk:in
!   plus diff mem management of: w:in rlv:in scratch:in vol:in
!                si:in sj:in sk:in
  subroutine sacatrisviscous_d()
!
!  diffusion term of the catris-aupoix density-corrected sa model,
!  which replaces saviscous when densitycorrsa == sadensitycatrisaupoix:
!
!    (1/sigma) [ d/dx_j (mu dnutilde/dx_j)
!                + d/dx_j (phi dphi/dx_j) + cb2 (dphi/dx_j)^2 ] / rho,
!    phi = sqrt(rho) nutilde,
!
!  catris, s. and aupoix, b., "density corrections for turbulence
!  models," aerospace science and technology, vol. 4, no. 1, 2000,
!  pp. 1-11, https://doi.org/10.1016/s1270-9638(00)00112-7
!  (sa-catris on the nasa turbulence modeling resource). the equation
!  for rho nutilde is divided by rho to obtain the non-conservative
!  form solved by adflow. the discretization follows saviscous:
!  cross derivatives are neglected and the terms in phi are written
!  as div((1+cb2) phi grad(phi)) - cb2 phi div(grad(phi)) with
!  nonnegative coefficients. for constant density the term reduces
!  to the standard sa diffusion term.
    use blockpointers
    use constants
    use paramturb
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: cb3inv, rhoinv
    real(kind=realtype) :: rhoinvd
    real(kind=realtype) :: voli, volmi, volpi, xm, ym, zm, xp, yp, zp
    real(kind=realtype) :: volid, volmid, volpid, xmd, ymd, zmd, xpd, &
&   ypd, zpd
    real(kind=realtype) :: xa, ya, za, ttm, ttp
    real(kind=realtype) :: xad, yad, zad, ttmd, ttpd
    real(kind=realtype) :: sqr0, sqrm, sqrp, phi0, phim, phip
    real(kind=realtype) :: sqr0d, sqrmd, sqrpd, phi0d, phimd, phipd
    real(kind=realtype) :: clm, clp, ctm, ctp
    real(kind=realtype) :: clmd, clpd, ctmd, ctpd
    real(kind=realtype) :: c1m, c1p, c10, b1, c1, d1
    real(kind=realtype) :: c1md, c1pd, c10d
    intrinsic sqrt
    intrinsic max
    real(kind=realtype) :: temp
    real(kind=realtype) :: temp0
    real(kind=realtype) :: temp1
    cb3inv = one/rsacb3
!
!       viscous terms in k-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in zeta-direction, i.e. along the
! line k = constant.
          temp = one/vol(i, j, k)
          volid = -(temp*vold(i, j, k)/vol(i, j, k))
          voli = temp
          temp = two/(vol(i, j, k)+vol(i, j, k-1))
          volmid = -(temp*(vold(i, j, k)+vold(i, j, k-1))/(vol(i, j, k)+&
&           vol(i, j, k-1)))
          volmi = temp
          temp = two/(vol(i, j, k)+vol(i, j, k+1))
          volpid = -(temp*(vold(i, j, k)+vold(i, j, k+1))/(vol(i, j, k)+&
&           vol(i, j, k+1)))
          volpi = temp
          temp = sk(i, j, k-1, 1)
          xmd = volmi*skd(i, j, k-1, 1) + temp*volmid
          xm = temp*volmi
          temp = sk(i, j, k-1, 2)
          ymd = volmi*skd(i, j, k-1, 2) + temp*volmid
          ym = temp*volmi
          temp = sk(i, j, k-1, 3)
          zmd = volmi*skd(i, j, k-1, 3) + temp*volmid
          zm = temp*volmi
          temp = sk(i, j, k, 1)
          xpd = volpi*skd(i, j, k, 1) + temp*volpid
          xp = temp*volpi
          temp = sk(i, j, k, 2)
          ypd = volpi*skd(i, j, k, 2) + temp*volpid
          yp = temp*volpi
          temp = sk(i, j, k, 3)
          zpd = volpi*skd(i, j, k, 3) + temp*volpid
          zp = temp*volpi
          temp = sk(i, j, k, 1) + sk(i, j, k-1, 1)
          xad = half*(voli*(skd(i, j, k, 1)+skd(i, j, k-1, 1))+temp*&
&           volid)
          xa = half*(temp*voli)
          temp = sk(i, j, k, 2) + sk(i, j, k-1, 2)
          yad = half*(voli*(skd(i, j, k, 2)+skd(i, j, k-1, 2))+temp*&
&           volid)
          ya = half*(temp*voli)
          temp = sk(i, j, k, 3) + sk(i, j, k-1, 3)
          zad = half*(voli*(skd(i, j, k, 3)+skd(i, j, k-1, 3))+temp*&
&           volid)
          za = half*(temp*voli)
          ttmd = xa*xmd + xm*xad + ya*ymd + ym*yad + za*zmd + zm*zad
          ttm = xm*xa + ym*ya + zm*za
          ttpd = xa*xpd + xp*xad + ya*ypd + yp*yad + za*zpd + zp*zad
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          temp = w(i, j, k, irho)
          temp0 = sqrt(temp)
          if (temp .eq. 0.0_8) then
            sqr0d = 0.0_8
          else
            sqr0d = wd(i, j, k, irho)/(2.0*temp0)
          end if
          sqr0 = temp0
          temp0 = w(i, j, k-1, irho)
          temp = sqrt(temp0)
          if (temp0 .eq. 0.0_8) then
            sqrmd = 0.0_8
          else
            sqrmd = wd(i, j, k-1, irho)/(2.0*temp)
          end if
          sqrm = temp
          temp0 = w(i, j, k+1, irho)
          temp = sqrt(temp0)
          if (temp0 .eq. 0.0_8) then
            sqrpd = 0.0_8
          else
            sqrpd = wd(i, j, k+1, irho)/(2.0*temp)
          end if
          sqrp = temp
          temp0 = w(i, j, k, itu1)
          phi0d = temp0*sqr0d + sqr0*wd(i, j, k, itu1)
          phi0 = sqr0*temp0
          temp0 = w(i, j, k-1, itu1)
          phimd = half*(temp0*sqrmd+sqrm*wd(i, j, k-1, itu1)+phi0d)
          phim = half*(sqrm*temp0+phi0)
          temp0 = w(i, j, k+1, itu1)
          phipd = half*(temp0*sqrpd+sqrp*wd(i, j, k+1, itu1)+phi0d)
          phip = half*(sqrp*temp0+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          temp0 = rlv(i, j, k-1) + rlv(i, j, k)
          clmd = half*cb3inv*(ttm*(rlvd(i, j, k-1)+rlvd(i, j, k))+temp0*&
&           ttmd)
          clm = half*cb3inv*(temp0*ttm)
          temp0 = rlv(i, j, k+1) + rlv(i, j, k)
          clpd = half*cb3inv*(ttp*(rlvd(i, j, k+1)+rlvd(i, j, k))+temp0*&
&           ttpd)
          clp = half*cb3inv*(temp0*ttp)
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctmd = -((clmd-clm*sqrmd/sqrm)/sqrm)
            ctm = -(clm/sqrm)
          else
            temp0 = (one+rsacb2)*phim - rsacb2*phi0
            ctmd = cb3inv*(ttm*((one+rsacb2)*phimd-rsacb2*phi0d)+temp0*&
&             ttmd)
            ctm = cb3inv*(temp0*ttm)
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctpd = -((clpd-clp*sqrpd/sqrp)/sqrp)
            ctp = -(clp/sqrp)
          else
            temp0 = (one+rsacb2)*phip - rsacb2*phi0
            ctpd = cb3inv*(ttp*((one+rsacb2)*phipd-rsacb2*phi0d)+temp0*&
&             ttpd)
            ctp = cb3inv*(temp0*ttp)
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          temp0 = one/w(i, j, k, irho)
          rhoinvd = -(temp0*wd(i, j, k, irho)/w(i, j, k, irho))
          rhoinv = temp0
          c1md = rhoinv*(clmd+sqrm*ctmd+ctm*sqrmd) + (clm+ctm*sqrm)*&
&           rhoinvd
          c1m = (clm+ctm*sqrm)*rhoinv
          c1pd = rhoinv*(clpd+sqrp*ctpd+ctp*sqrpd) + (clp+ctp*sqrp)*&
&           rhoinvd
          c1p = (clp+ctp*sqrp)*rhoinv
          temp0 = clm + clp + (ctm+ctp)*sqr0
          c10d = rhoinv*(clmd+clpd+sqr0*(ctmd+ctpd)+(ctm+ctp)*sqr0d) + &
&           temp0*rhoinvd
          c10 = temp0*rhoinv
          temp0 = w(i, j, k-1, itu1)
          temp = w(i, j, k+1, itu1)
          temp1 = w(i, j, k, itu1)
          scratchd(i, j, k, idvt) = scratchd(i, j, k, idvt) + temp0*c1md&
&           + c1m*wd(i, j, k-1, itu1) + temp*c1pd + c1p*wd(i, j, k+1, &
&           itu1) - temp1*c10d - c10*wd(i, j, k, itu1)
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*temp0 + &
&           c1p*temp - c10*temp1
        end do
      end do
    end do
!
!       viscous terms in j-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in eta-direction, i.e. along the
! line j = constant.
          temp1 = one/vol(i, j, k)
          volid = -(temp1*vold(i, j, k)/vol(i, j, k))
          voli = temp1
          temp1 = two/(vol(i, j, k)+vol(i, j-1, k))
          volmid = -(temp1*(vold(i, j, k)+vold(i, j-1, k))/(vol(i, j, k)&
&           +vol(i, j-1, k)))
          volmi = temp1
          temp1 = two/(vol(i, j, k)+vol(i, j+1, k))
          volpid = -(temp1*(vold(i, j, k)+vold(i, j+1, k))/(vol(i, j, k)&
&           +vol(i, j+1, k)))
          volpi = temp1
          temp1 = sj(i, j-1, k, 1)
          xmd = volmi*sjd(i, j-1, k, 1) + temp1*volmid
          xm = temp1*volmi
          temp1 = sj(i, j-1, k, 2)
          ymd = volmi*sjd(i, j-1, k, 2) + temp1*volmid
          ym = temp1*volmi
          temp1 = sj(i, j-1, k, 3)
          zmd = volmi*sjd(i, j-1, k, 3) + temp1*volmid
          zm = temp1*volmi
          temp1 = sj(i, j, k, 1)
          xpd = volpi*sjd(i, j, k, 1) + temp1*volpid
          xp = temp1*volpi
          temp1 = sj(i, j, k, 2)
          ypd = volpi*sjd(i, j, k, 2) + temp1*volpid
          yp = temp1*volpi
          temp1 = sj(i, j, k, 3)
          zpd = volpi*sjd(i, j, k, 3) + temp1*volpid
          zp = temp1*volpi
          temp1 = sj(i, j, k, 1) + sj(i, j-1, k, 1)
          xad = half*(voli*(sjd(i, j, k, 1)+sjd(i, j-1, k, 1))+temp1*&
&           volid)
          xa = half*(temp1*voli)
          temp1 = sj(i, j, k, 2) + sj(i, j-1, k, 2)
          yad = half*(voli*(sjd(i, j, k, 2)+sjd(i, j-1, k, 2))+temp1*&
&           volid)
          ya = half*(temp1*voli)
          temp1 = sj(i, j, k, 3) + sj(i, j-1, k, 3)
          zad = half*(voli*(sjd(i, j, k, 3)+sjd(i, j-1, k, 3))+temp1*&
&           volid)
          za = half*(temp1*voli)
          ttmd = xa*xmd + xm*xad + ya*ymd + ym*yad + za*zmd + zm*zad
          ttm = xm*xa + ym*ya + zm*za
          ttpd = xa*xpd + xp*xad + ya*ypd + yp*yad + za*zpd + zp*zad
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          temp1 = w(i, j, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqr0d = 0.0_8
          else
            sqr0d = wd(i, j, k, irho)/(2.0*temp0)
          end if
          sqr0 = temp0
          temp1 = w(i, j-1, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqrmd = 0.0_8
          else
            sqrmd = wd(i, j-1, k, irho)/(2.0*temp0)
          end if
          sqrm = temp0
          temp1 = w(i, j+1, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqrpd = 0.0_8
          else
            sqrpd = wd(i, j+1, k, irho)/(2.0*temp0)
          end if
          sqrp = temp0
          temp1 = w(i, j, k, itu1)
          phi0d = temp1*sqr0d + sqr0*wd(i, j, k, itu1)
          phi0 = sqr0*temp1
          temp1 = w(i, j-1, k, itu1)
          phimd = half*(temp1*sqrmd+sqrm*wd(i, j-1, k, itu1)+phi0d)
          phim = half*(sqrm*temp1+phi0)
          temp1 = w(i, j+1, k, itu1)
          phipd = half*(temp1*sqrpd+sqrp*wd(i, j+1, k, itu1)+phi0d)
          phip = half*(sqrp*temp1+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          temp1 = rlv(i, j-1, k) + rlv(i, j, k)
          clmd = half*cb3inv*(ttm*(rlvd(i, j-1, k)+rlvd(i, j, k))+temp1*&
&           ttmd)
          clm = half*cb3inv*(temp1*ttm)
          temp1 = rlv(i, j+1, k) + rlv(i, j, k)
          clpd = half*cb3inv*(ttp*(rlvd(i, j+1, k)+rlvd(i, j, k))+temp1*&
&           ttpd)
          clp = half*cb3inv*(temp1*ttp)
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctmd = -((clmd-clm*sqrmd/sqrm)/sqrm)
            ctm = -(clm/sqrm)
          else
            temp1 = (one+rsacb2)*phim - rsacb2*phi0
            ctmd = cb3inv*(ttm*((one+rsacb2)*phimd-rsacb2*phi0d)+temp1*&
&             ttmd)
            ctm = cb3inv*(temp1*ttm)
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctpd = -((clpd-clp*sqrpd/sqrp)/sqrp)
            ctp = -(clp/sqrp)
          else
            temp1 = (one+rsacb2)*phip - rsacb2*phi0
            ctpd = cb3inv*(ttp*((one+rsacb2)*phipd-rsacb2*phi0d)+temp1*&
&             ttpd)
            ctp = cb3inv*(temp1*ttp)
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          temp1 = one/w(i, j, k, irho)
          rhoinvd = -(temp1*wd(i, j, k, irho)/w(i, j, k, irho))
          rhoinv = temp1
          c1md = rhoinv*(clmd+sqrm*ctmd+ctm*sqrmd) + (clm+ctm*sqrm)*&
&           rhoinvd
          c1m = (clm+ctm*sqrm)*rhoinv
          c1pd = rhoinv*(clpd+sqrp*ctpd+ctp*sqrpd) + (clp+ctp*sqrp)*&
&           rhoinvd
          c1p = (clp+ctp*sqrp)*rhoinv
          temp1 = clm + clp + (ctm+ctp)*sqr0
          c10d = rhoinv*(clmd+clpd+sqr0*(ctmd+ctpd)+(ctm+ctp)*sqr0d) + &
&           temp1*rhoinvd
          c10 = temp1*rhoinv
          temp1 = w(i, j-1, k, itu1)
          temp0 = w(i, j+1, k, itu1)
          temp = w(i, j, k, itu1)
          scratchd(i, j, k, idvt) = scratchd(i, j, k, idvt) + temp1*c1md&
&           + c1m*wd(i, j-1, k, itu1) + temp0*c1pd + c1p*wd(i, j+1, k, &
&           itu1) - temp*c10d - c10*wd(i, j, k, itu1)
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*temp1 + &
&           c1p*temp0 - c10*temp
        end do
      end do
    end do
!
!       viscous terms in i-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in xi-direction, i.e. along the
! line i = constant.
          temp1 = one/vol(i, j, k)
          volid = -(temp1*vold(i, j, k)/vol(i, j, k))
          voli = temp1
          temp1 = two/(vol(i, j, k)+vol(i-1, j, k))
          volmid = -(temp1*(vold(i, j, k)+vold(i-1, j, k))/(vol(i, j, k)&
&           +vol(i-1, j, k)))
          volmi = temp1
          temp1 = two/(vol(i, j, k)+vol(i+1, j, k))
          volpid = -(temp1*(vold(i, j, k)+vold(i+1, j, k))/(vol(i, j, k)&
&           +vol(i+1, j, k)))
          volpi = temp1
          temp1 = si(i-1, j, k, 1)
          xmd = volmi*sid(i-1, j, k, 1) + temp1*volmid
          xm = temp1*volmi
          temp1 = si(i-1, j, k, 2)
          ymd = volmi*sid(i-1, j, k, 2) + temp1*volmid
          ym = temp1*volmi
          temp1 = si(i-1, j, k, 3)
          zmd = volmi*sid(i-1, j, k, 3) + temp1*volmid
          zm = temp1*volmi
          temp1 = si(i, j, k, 1)
          xpd = volpi*sid(i, j, k, 1) + temp1*volpid
          xp = temp1*volpi
          temp1 = si(i, j, k, 2)
          ypd = volpi*sid(i, j, k, 2) + temp1*volpid
          yp = temp1*volpi
          temp1 = si(i, j, k, 3)
          zpd = volpi*sid(i, j, k, 3) + temp1*volpid
          zp = temp1*volpi
          temp1 = si(i, j, k, 1) + si(i-1, j, k, 1)
          xad = half*(voli*(sid(i, j, k, 1)+sid(i-1, j, k, 1))+temp1*&
&           volid)
          xa = half*(temp1*voli)
          temp1 = si(i, j, k, 2) + si(i-1, j, k, 2)
          yad = half*(voli*(sid(i, j, k, 2)+sid(i-1, j, k, 2))+temp1*&
&           volid)
          ya = half*(temp1*voli)
          temp1 = si(i, j, k, 3) + si(i-1, j, k, 3)
          zad = half*(voli*(sid(i, j, k, 3)+sid(i-1, j, k, 3))+temp1*&
&           volid)
          za = half*(temp1*voli)
          ttmd = xa*xmd + xm*xad + ya*ymd + ym*yad + za*zmd + zm*zad
          ttm = xm*xa + ym*ya + zm*za
          ttpd = xa*xpd + xp*xad + ya*ypd + yp*yad + za*zpd + zp*zad
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          temp1 = w(i, j, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqr0d = 0.0_8
          else
            sqr0d = wd(i, j, k, irho)/(2.0*temp0)
          end if
          sqr0 = temp0
          temp1 = w(i-1, j, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqrmd = 0.0_8
          else
            sqrmd = wd(i-1, j, k, irho)/(2.0*temp0)
          end if
          sqrm = temp0
          temp1 = w(i+1, j, k, irho)
          temp0 = sqrt(temp1)
          if (temp1 .eq. 0.0_8) then
            sqrpd = 0.0_8
          else
            sqrpd = wd(i+1, j, k, irho)/(2.0*temp0)
          end if
          sqrp = temp0
          temp1 = w(i, j, k, itu1)
          phi0d = temp1*sqr0d + sqr0*wd(i, j, k, itu1)
          phi0 = sqr0*temp1
          temp1 = w(i-1, j, k, itu1)
          phimd = half*(temp1*sqrmd+sqrm*wd(i-1, j, k, itu1)+phi0d)
          phim = half*(sqrm*temp1+phi0)
          temp1 = w(i+1, j, k, itu1)
          phipd = half*(temp1*sqrpd+sqrp*wd(i+1, j, k, itu1)+phi0d)
          phip = half*(sqrp*temp1+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          temp1 = rlv(i-1, j, k) + rlv(i, j, k)
          clmd = half*cb3inv*(ttm*(rlvd(i-1, j, k)+rlvd(i, j, k))+temp1*&
&           ttmd)
          clm = half*cb3inv*(temp1*ttm)
          temp1 = rlv(i+1, j, k) + rlv(i, j, k)
          clpd = half*cb3inv*(ttp*(rlvd(i+1, j, k)+rlvd(i, j, k))+temp1*&
&           ttpd)
          clp = half*cb3inv*(temp1*ttp)
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctmd = -((clmd-clm*sqrmd/sqrm)/sqrm)
            ctm = -(clm/sqrm)
          else
            temp1 = (one+rsacb2)*phim - rsacb2*phi0
            ctmd = cb3inv*(ttm*((one+rsacb2)*phimd-rsacb2*phi0d)+temp1*&
&             ttmd)
            ctm = cb3inv*(temp1*ttm)
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctpd = -((clpd-clp*sqrpd/sqrp)/sqrp)
            ctp = -(clp/sqrp)
          else
            temp1 = (one+rsacb2)*phip - rsacb2*phi0
            ctpd = cb3inv*(ttp*((one+rsacb2)*phipd-rsacb2*phi0d)+temp1*&
&             ttpd)
            ctp = cb3inv*(temp1*ttp)
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          temp1 = one/w(i, j, k, irho)
          rhoinvd = -(temp1*wd(i, j, k, irho)/w(i, j, k, irho))
          rhoinv = temp1
          c1md = rhoinv*(clmd+sqrm*ctmd+ctm*sqrmd) + (clm+ctm*sqrm)*&
&           rhoinvd
          c1m = (clm+ctm*sqrm)*rhoinv
          c1pd = rhoinv*(clpd+sqrp*ctpd+ctp*sqrpd) + (clp+ctp*sqrp)*&
&           rhoinvd
          c1p = (clp+ctp*sqrp)*rhoinv
          temp1 = clm + clp + (ctm+ctp)*sqr0
          c10d = rhoinv*(clmd+clpd+sqr0*(ctmd+ctpd)+(ctm+ctp)*sqr0d) + &
&           temp1*rhoinvd
          c10 = temp1*rhoinv
          temp1 = w(i-1, j, k, itu1)
          temp0 = w(i+1, j, k, itu1)
          temp = w(i, j, k, itu1)
          scratchd(i, j, k, idvt) = scratchd(i, j, k, idvt) + temp1*c1md&
&           + c1m*wd(i-1, j, k, itu1) + temp0*c1pd + c1p*wd(i+1, j, k, &
&           itu1) - temp*c10d - c10*wd(i, j, k, itu1)
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*temp1 + &
&           c1p*temp0 - c10*temp
        end do
      end do
    end do
  end subroutine sacatrisviscous_d

  subroutine sacatrisviscous()
!
!  diffusion term of the catris-aupoix density-corrected sa model,
!  which replaces saviscous when densitycorrsa == sadensitycatrisaupoix:
!
!    (1/sigma) [ d/dx_j (mu dnutilde/dx_j)
!                + d/dx_j (phi dphi/dx_j) + cb2 (dphi/dx_j)^2 ] / rho,
!    phi = sqrt(rho) nutilde,
!
!  catris, s. and aupoix, b., "density corrections for turbulence
!  models," aerospace science and technology, vol. 4, no. 1, 2000,
!  pp. 1-11, https://doi.org/10.1016/s1270-9638(00)00112-7
!  (sa-catris on the nasa turbulence modeling resource). the equation
!  for rho nutilde is divided by rho to obtain the non-conservative
!  form solved by adflow. the discretization follows saviscous:
!  cross derivatives are neglected and the terms in phi are written
!  as div((1+cb2) phi grad(phi)) - cb2 phi div(grad(phi)) with
!  nonnegative coefficients. for constant density the term reduces
!  to the standard sa diffusion term.
    use blockpointers
    use constants
    use paramturb
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: cb3inv, rhoinv
    real(kind=realtype) :: voli, volmi, volpi, xm, ym, zm, xp, yp, zp
    real(kind=realtype) :: xa, ya, za, ttm, ttp
    real(kind=realtype) :: sqr0, sqrm, sqrp, phi0, phim, phip
    real(kind=realtype) :: clm, clp, ctm, ctp
    real(kind=realtype) :: c1m, c1p, c10, b1, c1, d1
    intrinsic sqrt
    intrinsic max
    cb3inv = one/rsacb3
!
!       viscous terms in k-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in zeta-direction, i.e. along the
! line k = constant.
          voli = one/vol(i, j, k)
          volmi = two/(vol(i, j, k)+vol(i, j, k-1))
          volpi = two/(vol(i, j, k)+vol(i, j, k+1))
          xm = sk(i, j, k-1, 1)*volmi
          ym = sk(i, j, k-1, 2)*volmi
          zm = sk(i, j, k-1, 3)*volmi
          xp = sk(i, j, k, 1)*volpi
          yp = sk(i, j, k, 2)*volpi
          zp = sk(i, j, k, 3)*volpi
          xa = half*(sk(i, j, k, 1)+sk(i, j, k-1, 1))*voli
          ya = half*(sk(i, j, k, 2)+sk(i, j, k-1, 2))*voli
          za = half*(sk(i, j, k, 3)+sk(i, j, k-1, 3))*voli
          ttm = xm*xa + ym*ya + zm*za
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          sqr0 = sqrt(w(i, j, k, irho))
          sqrm = sqrt(w(i, j, k-1, irho))
          sqrp = sqrt(w(i, j, k+1, irho))
          phi0 = sqr0*w(i, j, k, itu1)
          phim = half*(sqrm*w(i, j, k-1, itu1)+phi0)
          phip = half*(sqrp*w(i, j, k+1, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          clm = half*(rlv(i, j, k-1)+rlv(i, j, k))*ttm*cb3inv
          clp = half*(rlv(i, j, k+1)+rlv(i, j, k))*ttp*cb3inv
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctm = -(clm/sqrm)
          else
            ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctp = -(clp/sqrp)
          else
            ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          rhoinv = one/w(i, j, k, irho)
          c1m = (clm+ctm*sqrm)*rhoinv
          c1p = (clp+ctp*sqrp)*rhoinv
          c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i, j, &
&           k-1, itu1) - c10*w(i, j, k, itu1) + c1p*w(i, j, k+1, itu1)
        end do
      end do
    end do
!
!       viscous terms in j-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in eta-direction, i.e. along the
! line j = constant.
          voli = one/vol(i, j, k)
          volmi = two/(vol(i, j, k)+vol(i, j-1, k))
          volpi = two/(vol(i, j, k)+vol(i, j+1, k))
          xm = sj(i, j-1, k, 1)*volmi
          ym = sj(i, j-1, k, 2)*volmi
          zm = sj(i, j-1, k, 3)*volmi
          xp = sj(i, j, k, 1)*volpi
          yp = sj(i, j, k, 2)*volpi
          zp = sj(i, j, k, 3)*volpi
          xa = half*(sj(i, j, k, 1)+sj(i, j-1, k, 1))*voli
          ya = half*(sj(i, j, k, 2)+sj(i, j-1, k, 2))*voli
          za = half*(sj(i, j, k, 3)+sj(i, j-1, k, 3))*voli
          ttm = xm*xa + ym*ya + zm*za
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          sqr0 = sqrt(w(i, j, k, irho))
          sqrm = sqrt(w(i, j-1, k, irho))
          sqrp = sqrt(w(i, j+1, k, irho))
          phi0 = sqr0*w(i, j, k, itu1)
          phim = half*(sqrm*w(i, j-1, k, itu1)+phi0)
          phip = half*(sqrp*w(i, j+1, k, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          clm = half*(rlv(i, j-1, k)+rlv(i, j, k))*ttm*cb3inv
          clp = half*(rlv(i, j+1, k)+rlv(i, j, k))*ttp*cb3inv
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctm = -(clm/sqrm)
          else
            ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctp = -(clp/sqrp)
          else
            ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          rhoinv = one/w(i, j, k, irho)
          c1m = (clm+ctm*sqrm)*rhoinv
          c1p = (clp+ctp*sqrp)*rhoinv
          c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i, j-1&
&           , k, itu1) - c10*w(i, j, k, itu1) + c1p*w(i, j+1, k, itu1)
        end do
      end do
    end do
!
!       viscous terms in i-direction.
!
    do k=2,kl
      do j=2,jl
        do i=2,il
! compute the metrics in xi-direction, i.e. along the
! line i = constant.
          voli = one/vol(i, j, k)
          volmi = two/(vol(i, j, k)+vol(i-1, j, k))
          volpi = two/(vol(i, j, k)+vol(i+1, j, k))
          xm = si(i-1, j, k, 1)*volmi
          ym = si(i-1, j, k, 2)*volmi
          zm = si(i-1, j, k, 3)*volmi
          xp = si(i, j, k, 1)*volpi
          yp = si(i, j, k, 2)*volpi
          zp = si(i, j, k, 3)*volpi
          xa = half*(si(i, j, k, 1)+si(i-1, j, k, 1))*voli
          ya = half*(si(i, j, k, 2)+si(i-1, j, k, 2))*voli
          za = half*(si(i, j, k, 3)+si(i-1, j, k, 3))*voli
          ttm = xm*xa + ym*ya + zm*za
          ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
          sqr0 = sqrt(w(i, j, k, irho))
          sqrm = sqrt(w(i-1, j, k, irho))
          sqrp = sqrt(w(i+1, j, k, irho))
          phi0 = sqr0*w(i, j, k, itu1)
          phim = half*(sqrm*w(i-1, j, k, itu1)+phi0)
          phip = half*(sqrp*w(i+1, j, k, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
          clm = half*(rlv(i-1, j, k)+rlv(i, j, k))*ttm*cb3inv
          clp = half*(rlv(i+1, j, k)+rlv(i, j, k))*ttp*cb3inv
          if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm&
&             )) then
            ctm = -(clm/sqrm)
          else
            ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
          end if
          if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp&
&             )) then
            ctp = -(clp/sqrp)
          else
            ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
          end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
          rhoinv = one/w(i, j, k, irho)
          c1m = (clm+ctm*sqrm)*rhoinv
          c1p = (clp+ctp*sqrp)*rhoinv
          c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
          scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i-1, j&
&           , k, itu1) - c10*w(i, j, k, itu1) + c1p*w(i+1, j, k, itu1)
        end do
      end do
    end do
  end subroutine sacatrisviscous

!  differentiation of sadensitycorrectionsource in forward (tangent) mode (with options i4 dr8 r8):
!   variations   of useful results: *scratch
!   with respect to varying inputs: *w *rlv *scratch *vol *si *sj
!                *sk
!   rw status of diff variables: *w:in *rlv:in *scratch:in-out
!                *vol:in *si:in *sj:in *sk:in
!   plus diff mem management of: w:in rlv:in scratch:in vol:in
!                si:in sj:in sk:in
  subroutine sadensitycorrectionsource_d()
!
!  source terms of the density corrections of the sa model that are
!  not part of sacatrisviscous, written in the non-conservative
!  form for nutilde solved by adflow.
!
!  densitycorrsa == sadensitycatrisaupoix: the original catris-aupoix
!  model has d(rho nutilde)/dt on the left hand side (tmr:
!  sa-noft2-catris), which differs from rho d(nutilde)/dt by
!  nutilde d(rho)/dt = -rho nutilde div(u). the term nutilde div(u)
!  is therefore added; without it (sadensitycatrisaupoixcons, tmr:
!  sa-noft2-catriscons, waligura et al. aiaa 2022-0587) the model
!  is conservative in rho nutilde.
!
!  densitycorrsa == sadensityconservative, sadensitycatris1999 or
!  sadensityseror: density-gradient diffusion terms. adflow's
!  standard diffusion term, multiplied by rho, equals the
!  conservative form
!
!    (1/sigma) [ d/dx_j (rho (nu + nutilde) dnutilde/dx_j)
!                + cb2 rho (dnutilde/dx_j)^2 ]
!
!  minus the cross term (1/sigma) (nu + nutilde) (drho/dx_j)(dnutilde/dx_j)
!  (allmaras, johnson and spalart, iccfd7-1902, 2012). the following
!  terms are therefore added to the source, divided by rho:
!
!    conservative:  (1/sigma) (nu + nutilde) grad(rho).grad(nutilde)
!    catris-1999:   conservative + (cb2/sigma) nutilde grad(rho).grad(nutilde)
!                   (catris, phd thesis, ensae 1999; xue et al., aiaa j.
!                   62(1), 2024, eq. 5)
!    seror:         catris-1999 + (cb2/sigma) grad(mu).grad(nutilde)
!                   (seror et al., j. aircraft 42(1), 2005)
!
!  all terms are treated explicitly (no contribution to qq).
    use blockpointers
    use constants
    use paramturb
    use inputphysics, only : densitycorrsa
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: fact, rhox, rhoy, rhoz, nux, nuy, nuz, mux, &
&   muy, muz
