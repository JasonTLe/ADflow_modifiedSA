        phi0d = phi0d - rsacb2*tempd
      end if
      tempd = half*ttp*cb3inv*clpd
      rlvd(i, j, k+1) = rlvd(i, j, k+1) + tempd
      rlvd(i, j, k) = rlvd(i, j, k) + tempd
      tempd = half*ttm*cb3inv*clmd
      rlvd(i, j, k-1) = rlvd(i, j, k-1) + tempd
      rlvd(i, j, k) = rlvd(i, j, k) + tempd
      tempd = half*phipd
      sqrpd = sqrpd + w(i, j, k+1, itu1)*tempd
      wd(i, j, k+1, itu1) = wd(i, j, k+1, itu1) + sqrp*tempd
      phi0d = phi0d + tempd
      tempd = half*phimd
      sqrmd = sqrmd + w(i, j, k-1, itu1)*tempd
      wd(i, j, k-1, itu1) = wd(i, j, k-1, itu1) + sqrm*tempd
      phi0d = phi0d + tempd
      sqr0d = sqr0d + w(i, j, k, itu1)*phi0d
      wd(i, j, k, itu1) = wd(i, j, k, itu1) + sqr0*phi0d
      if (.not.w(i, j, k+1, irho) .eq. 0.0_8) wd(i, j, k+1, irho) = wd(i&
&         , j, k+1, irho) + sqrpd/(2.0*sqrt(w(i, j, k+1, irho)))
      if (.not.w(i, j, k-1, irho) .eq. 0.0_8) wd(i, j, k-1, irho) = wd(i&
&         , j, k-1, irho) + sqrmd/(2.0*sqrt(w(i, j, k-1, irho)))
      if (.not.w(i, j, k, irho) .eq. 0.0_8) wd(i, j, k, irho) = wd(i, j&
&         , k, irho) + sqr0d/(2.0*sqrt(w(i, j, k, irho)))
    end do
  end subroutine sacatrisviscous_fast_b

  subroutine sacatrisviscous()
!
!  diffusion term of the catris-aupoix density-corrected sa model,
!  which replaces saviscous when densitycorrsa == sadensitycatrisaupoix:
!
!    (1/sigma) [ d/dx_j (mu dnutilde/dx_j)
!                + d/dx_j (phi dphi/dx_j) + cb2 (dphi/dx_j)^2 ] / rho,
!    phi = sqrt(rho) nutilde,
!
!  catris, s. and aupoix, b., "density corrections for turbulence
!  models," aerospace science and technology, vol. 4, no. 1, 2000,
!  pp. 1-11, https://doi.org/10.1016/s1270-9638(00)00112-7
!  (sa-catris on the nasa turbulence modeling resource). the equation
!  for rho nutilde is divided by rho to obtain the non-conservative
!  form solved by adflow. the discretization follows saviscous:
!  cross derivatives are neglected and the terms in phi are written
!  as div((1+cb2) phi grad(phi)) - cb2 phi div(grad(phi)) with
!  nonnegative coefficients. for constant density the term reduces
!  to the standard sa diffusion term.
    use blockpointers
    use constants
    use paramturb
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: cb3inv, rhoinv
    real(kind=realtype) :: voli, volmi, volpi, xm, ym, zm, xp, yp, zp
    real(kind=realtype) :: xa, ya, za, ttm, ttp
    real(kind=realtype) :: sqr0, sqrm, sqrp, phi0, phim, phip
    real(kind=realtype) :: clm, clp, ctm, ctp
    real(kind=realtype) :: c1m, c1p, c10, b1, c1, d1
    intrinsic mod
    intrinsic sqrt
    intrinsic max
    cb3inv = one/rsacb3
!$ad ii-loop
!
!       viscous terms in k-direction.
!
    do ii=0,nx*ny*nz-1
      i = mod(ii, nx) + 2
      j = mod(ii/nx, ny) + 2
      k = ii/(nx*ny) + 2
! compute the metrics in zeta-direction, i.e. along the
! line k = constant.
      voli = one/vol(i, j, k)
      volmi = two/(vol(i, j, k)+vol(i, j, k-1))
      volpi = two/(vol(i, j, k)+vol(i, j, k+1))
      xm = sk(i, j, k-1, 1)*volmi
      ym = sk(i, j, k-1, 2)*volmi
      zm = sk(i, j, k-1, 3)*volmi
      xp = sk(i, j, k, 1)*volpi
      yp = sk(i, j, k, 2)*volpi
      zp = sk(i, j, k, 3)*volpi
      xa = half*(sk(i, j, k, 1)+sk(i, j, k-1, 1))*voli
      ya = half*(sk(i, j, k, 2)+sk(i, j, k-1, 2))*voli
      za = half*(sk(i, j, k, 3)+sk(i, j, k-1, 3))*voli
      ttm = xm*xa + ym*ya + zm*za
      ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
      sqr0 = sqrt(w(i, j, k, irho))
      sqrm = sqrt(w(i, j, k-1, irho))
      sqrp = sqrt(w(i, j, k+1, irho))
      phi0 = sqr0*w(i, j, k, itu1)
      phim = half*(sqrm*w(i, j, k-1, itu1)+phi0)
      phip = half*(sqrp*w(i, j, k+1, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
      clm = half*(rlv(i, j, k-1)+rlv(i, j, k))*ttm*cb3inv
      clp = half*(rlv(i, j, k+1)+rlv(i, j, k))*ttp*cb3inv
      if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm)) &
&     then
        ctm = -(clm/sqrm)
      else
        ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
      end if
      if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp)) &
&     then
        ctp = -(clp/sqrp)
      else
        ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
      end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
      rhoinv = one/w(i, j, k, irho)
      c1m = (clm+ctm*sqrm)*rhoinv
      c1p = (clp+ctp*sqrp)*rhoinv
      c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
      scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i, j, k-1&
&       , itu1) - c10*w(i, j, k, itu1) + c1p*w(i, j, k+1, itu1)
    end do
!$ad ii-loop
!
!       viscous terms in j-direction.
!
    do ii=0,nx*ny*nz-1
      i = mod(ii, nx) + 2
      j = mod(ii/nx, ny) + 2
      k = ii/(nx*ny) + 2
! compute the metrics in eta-direction, i.e. along the
! line j = constant.
      voli = one/vol(i, j, k)
      volmi = two/(vol(i, j, k)+vol(i, j-1, k))
      volpi = two/(vol(i, j, k)+vol(i, j+1, k))
      xm = sj(i, j-1, k, 1)*volmi
      ym = sj(i, j-1, k, 2)*volmi
      zm = sj(i, j-1, k, 3)*volmi
      xp = sj(i, j, k, 1)*volpi
      yp = sj(i, j, k, 2)*volpi
      zp = sj(i, j, k, 3)*volpi
      xa = half*(sj(i, j, k, 1)+sj(i, j-1, k, 1))*voli
      ya = half*(sj(i, j, k, 2)+sj(i, j-1, k, 2))*voli
      za = half*(sj(i, j, k, 3)+sj(i, j-1, k, 3))*voli
      ttm = xm*xa + ym*ya + zm*za
      ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
      sqr0 = sqrt(w(i, j, k, irho))
      sqrm = sqrt(w(i, j-1, k, irho))
      sqrp = sqrt(w(i, j+1, k, irho))
      phi0 = sqr0*w(i, j, k, itu1)
      phim = half*(sqrm*w(i, j-1, k, itu1)+phi0)
      phip = half*(sqrp*w(i, j+1, k, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
      clm = half*(rlv(i, j-1, k)+rlv(i, j, k))*ttm*cb3inv
      clp = half*(rlv(i, j+1, k)+rlv(i, j, k))*ttp*cb3inv
      if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm)) &
&     then
        ctm = -(clm/sqrm)
      else
        ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
      end if
      if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp)) &
&     then
        ctp = -(clp/sqrp)
      else
        ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
      end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
      rhoinv = one/w(i, j, k, irho)
      c1m = (clm+ctm*sqrm)*rhoinv
      c1p = (clp+ctp*sqrp)*rhoinv
      c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
      scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i, j-1, k&
&       , itu1) - c10*w(i, j, k, itu1) + c1p*w(i, j+1, k, itu1)
    end do
!$ad ii-loop
!
!       viscous terms in i-direction.
!
    do ii=0,nx*ny*nz-1
      i = mod(ii, nx) + 2
      j = mod(ii/nx, ny) + 2
      k = ii/(nx*ny) + 2
! compute the metrics in xi-direction, i.e. along the
! line i = constant.
      voli = one/vol(i, j, k)
      volmi = two/(vol(i, j, k)+vol(i-1, j, k))
      volpi = two/(vol(i, j, k)+vol(i+1, j, k))
      xm = si(i-1, j, k, 1)*volmi
      ym = si(i-1, j, k, 2)*volmi
      zm = si(i-1, j, k, 3)*volmi
      xp = si(i, j, k, 1)*volpi
      yp = si(i, j, k, 2)*volpi
      zp = si(i, j, k, 3)*volpi
      xa = half*(si(i, j, k, 1)+si(i-1, j, k, 1))*voli
      ya = half*(si(i, j, k, 2)+si(i-1, j, k, 2))*voli
      za = half*(si(i, j, k, 3)+si(i-1, j, k, 3))*voli
      ttm = xm*xa + ym*ya + zm*za
      ttp = xp*xa + yp*ya + zp*za
! phi = sqrt(rho) nutilde in the cell and at the faces.
      sqr0 = sqrt(w(i, j, k, irho))
      sqrm = sqrt(w(i-1, j, k, irho))
      sqrp = sqrt(w(i+1, j, k, irho))
      phi0 = sqr0*w(i, j, k, itu1)
      phim = half*(sqrm*w(i-1, j, k, itu1)+phi0)
      phip = half*(sqrp*w(i+1, j, k, itu1)+phi0)
! laminar diffusion coefficients, mu/sigma at the faces.
      clm = half*(rlv(i-1, j, k)+rlv(i, j, k))*ttm*cb3inv
      clp = half*(rlv(i+1, j, k)+rlv(i, j, k))*ttp*cb3inv
      if (((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv .lt. -(clm/sqrm)) &
&     then
        ctm = -(clm/sqrm)
      else
        ctm = ((one+rsacb2)*phim-rsacb2*phi0)*ttm*cb3inv
      end if
      if (((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv .lt. -(clp/sqrp)) &
&     then
        ctp = -(clp/sqrp)
      else
        ctp = ((one+rsacb2)*phip-rsacb2*phi0)*ttp*cb3inv
      end if
! coefficients of nutilde in the neighbours and the cell
! itself; the whole term is divided by rho.
      rhoinv = one/w(i, j, k, irho)
      c1m = (clm+ctm*sqrm)*rhoinv
      c1p = (clp+ctp*sqrp)*rhoinv
      c10 = (clm+clp+(ctm+ctp)*sqr0)*rhoinv
      scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + c1m*w(i-1, j, k&
&       , itu1) - c10*w(i, j, k, itu1) + c1p*w(i+1, j, k, itu1)
    end do
  end subroutine sacatrisviscous

!  differentiation of sadensitycorrectionsource in reverse (adjoint) mode (with options noisize i4 dr8 r8):
!   gradient     of useful results: *w *rlv *scratch
!   with respect to varying inputs: *w *rlv *scratch
!   rw status of diff variables: *w:incr *rlv:incr *scratch:in-out
!   plus diff mem management of: w:in rlv:in scratch:in
  subroutine sadensitycorrectionsource_fast_b()
!
!  source terms of the density corrections of the sa model that are
!  not part of sacatrisviscous, written in the non-conservative
!  form for nutilde solved by adflow.
!
!  densitycorrsa == sadensitycatrisaupoix: the original catris-aupoix
!  model has d(rho nutilde)/dt on the left hand side (tmr:
!  sa-noft2-catris), which differs from rho d(nutilde)/dt by
!  nutilde d(rho)/dt = -rho nutilde div(u). the term nutilde div(u)
!  is therefore added; without it (sadensitycatrisaupoixcons, tmr:
!  sa-noft2-catriscons, waligura et al. aiaa 2022-0587) the model
!  is conservative in rho nutilde.
!
!  densitycorrsa == sadensityconservative, sadensitycatris1999 or
!  sadensityseror: density-gradient diffusion terms. adflow's
!  standard diffusion term, multiplied by rho, equals the
!  conservative form
!
!    (1/sigma) [ d/dx_j (rho (nu + nutilde) dnutilde/dx_j)
!                + cb2 rho (dnutilde/dx_j)^2 ]
!
!  minus the cross term (1/sigma) (nu + nutilde) (drho/dx_j)(dnutilde/dx_j)
!  (allmaras, johnson and spalart, iccfd7-1902, 2012). the following
!  terms are therefore added to the source, divided by rho:
!
!    conservative:  (1/sigma) (nu + nutilde) grad(rho).grad(nutilde)
!    catris-1999:   conservative + (cb2/sigma) nutilde grad(rho).grad(nutilde)
!                   (catris, phd thesis, ensae 1999; xue et al., aiaa j.
!                   62(1), 2024, eq. 5)
!    seror:         catris-1999 + (cb2/sigma) grad(mu).grad(nutilde)
!                   (seror et al., j. aircraft 42(1), 2005)
!
!  all terms are treated explicitly (no contribution to qq).
    use blockpointers
    use constants
    use paramturb
    use inputphysics, only : densitycorrsa
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: fact, rhox, rhoy, rhoz, nux, nuy, nuz, mux, &
&   muy, muz
    real(kind=realtype) :: rhoxd, rhoyd, rhozd, nuxd, nuyd, nuzd, muxd, &
&   muyd, muzd
    real(kind=realtype) :: gradrhonu, nu, coef, src, cb3inv, divu
    real(kind=realtype) :: gradrhonud, nud, coefd, srcd, divud
    intrinsic mod
    real(kind=realtype) :: temp
    real(kind=realtype) :: tempd
    real(kind=realtype) :: tempd0
    integer :: branch
    cb3inv = one/rsacb3
!$bwd-of ii-loop 
    do ii=0,nx*ny*nz-1
      i = mod(ii, nx) + 2
      j = mod(ii/nx, ny) + 2
      k = ii/(nx*ny) + 2
      fact = half/vol(i, j, k)
      if (densitycorrsa .eq. sadensitycatrisaupoix) then
! original (non-conservative) form of the
! catris-aupoix model, d(rho nutilde)/dt on the left
! hand side: divided by rho this adds nutilde div(u)
! to the equation for nutilde solved here.
        divu = fact*(w(i+1, j, k, ivx)*si(i, j, k, 1)-w(i-1, j, k, ivx)*&
&         si(i-1, j, k, 1)+w(i, j+1, k, ivx)*sj(i, j, k, 1)-w(i, j-1, k&
&         , ivx)*sj(i, j-1, k, 1)+w(i, j, k+1, ivx)*sk(i, j, k, 1)-w(i, &
&         j, k-1, ivx)*sk(i, j, k-1, 1)+w(i+1, j, k, ivy)*si(i, j, k, 2)&
&         -w(i-1, j, k, ivy)*si(i-1, j, k, 2)+w(i, j+1, k, ivy)*sj(i, j&
&         , k, 2)-w(i, j-1, k, ivy)*sj(i, j-1, k, 2)+w(i, j, k+1, ivy)*&
&         sk(i, j, k, 2)-w(i, j, k-1, ivy)*sk(i, j, k-1, 2)+w(i+1, j, k&
&         , ivz)*si(i, j, k, 3)-w(i-1, j, k, ivz)*si(i-1, j, k, 3)+w(i, &
&         j+1, k, ivz)*sj(i, j, k, 3)-w(i, j-1, k, ivz)*sj(i, j-1, k, 3)&
&         +w(i, j, k+1, ivz)*sk(i, j, k, 3)-w(i, j, k-1, ivz)*sk(i, j, k&
&         -1, 3))
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 0
      else
! cell-centred gradients of rho, nutilde and mu
! (green-gauss with the neighbouring cell values,
! see sasource).
        rhox = fact*(w(i+1, j, k, irho)*si(i, j, k, 1)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 1)+w(i, j+1, k, irho)*sj(i, j, k, 1)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 1)+w(i, j, k+1, irho)*sk(i, j, k, 1)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 1))
        rhoy = fact*(w(i+1, j, k, irho)*si(i, j, k, 2)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 2)+w(i, j+1, k, irho)*sj(i, j, k, 2)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 2)+w(i, j, k+1, irho)*sk(i, j, k, 2)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 2))
        rhoz = fact*(w(i+1, j, k, irho)*si(i, j, k, 3)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 3)+w(i, j+1, k, irho)*sj(i, j, k, 3)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 3)+w(i, j, k+1, irho)*sk(i, j, k, 3)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 3))
        nux = fact*(w(i+1, j, k, itu1)*si(i, j, k, 1)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 1)+w(i, j+1, k, itu1)*sj(i, j, k, 1)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 1)+w(i, j, k+1, itu1)*sk(i, j, k, 1)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 1))
        nuy = fact*(w(i+1, j, k, itu1)*si(i, j, k, 2)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 2)+w(i, j+1, k, itu1)*sj(i, j, k, 2)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 2)+w(i, j, k+1, itu1)*sk(i, j, k, 2)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 2))
        nuz = fact*(w(i+1, j, k, itu1)*si(i, j, k, 3)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 3)+w(i, j+1, k, itu1)*sj(i, j, k, 3)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 3)+w(i, j, k+1, itu1)*sk(i, j, k, 3)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 3))
        gradrhonu = rhox*nux + rhoy*nuy + rhoz*nuz
! (nu + nutilde) grad(rho).grad(nutilde): conservative form
        nu = rlv(i, j, k)/w(i, j, k, irho)
        coef = nu + w(i, j, k, itu1)
! + cb2 nutilde grad(rho).grad(nutilde): catris (1999)
        if (densitycorrsa .eq. sadensitycatris1999 .or. densitycorrsa &
&           .eq. sadensityseror) then
          coef = coef + rsacb2*w(i, j, k, itu1)
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 0
        else
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 1
        end if
        src = coef*gradrhonu
! + cb2 grad(mu).grad(nutilde): seror et al. (2005)
        if (densitycorrsa .eq. sadensityseror) then
          mux = fact*(rlv(i+1, j, k)*si(i, j, k, 1)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 1)+rlv(i, j+1, k)*sj(i, j, k, 1)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 1)+rlv(i, j, k+1)*sk(i, j, k, 1)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 1))
          muy = fact*(rlv(i+1, j, k)*si(i, j, k, 2)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 2)+rlv(i, j+1, k)*sj(i, j, k, 2)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 2)+rlv(i, j, k+1)*sk(i, j, k, 2)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 2))
          muz = fact*(rlv(i+1, j, k)*si(i, j, k, 3)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 3)+rlv(i, j+1, k)*sj(i, j, k, 3)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 3)+rlv(i, j, k+1)*sk(i, j, k, 3)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 3))
          src = src + rsacb2*(mux*nux+muy*nuy+muz*nuz)
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 0
        else
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 1
        end if
myIntPtr = myIntPtr + 1
 myIntStack(myIntPtr) = 1
      end if
      srcd = scratchd(i, j, k, idvt)
branch = myIntStack(myIntPtr)
 myIntPtr = myIntPtr - 1
      if (branch .eq. 0) then
