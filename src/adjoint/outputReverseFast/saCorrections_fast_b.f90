  subroutine sadensitycorrectionsource()
!
!  source terms of the density corrections of the sa model that are
!  not part of sacatrisviscous, written in the non-conservative
!  form for nutilde solved by adflow.
!
!  densitycorrsa == sadensitycatrisaupoix: the original catris-aupoix
!  model has d(rho nutilde)/dt on the left hand side (tmr:
!  sa-noft2-catris), which differs from rho d(nutilde)/dt by
!  nutilde d(rho)/dt = -rho nutilde div(u). the term nutilde div(u)
!  is therefore added; without it (sadensitycatrisaupoixcons, tmr:
!  sa-noft2-catriscons, waligura et al. aiaa 2022-0587) the model
!  is conservative in rho nutilde.
!
!  densitycorrsa == sadensityconservative, sadensitycatris1999 or
!  sadensityseror: density-gradient diffusion terms. adflow's
!  standard diffusion term, multiplied by rho, equals the
!  conservative form
!
!    (1/sigma) [ d/dx_j (rho (nu + nutilde) dnutilde/dx_j)
!                + cb2 rho (dnutilde/dx_j)^2 ]
!
!  minus the cross term (1/sigma) (nu + nutilde) (drho/dx_j)(dnutilde/dx_j)
!  (allmaras, johnson and spalart, iccfd7-1902, 2012). the following
!  terms are therefore added to the source, divided by rho:
!
!    conservative:  (1/sigma) (nu + nutilde) grad(rho).grad(nutilde)
!    catris-1999:   conservative + (cb2/sigma) nutilde grad(rho).grad(nutilde)
!                   (catris, phd thesis, ensae 1999; xue et al., aiaa j.
!                   62(1), 2024, eq. 5)
!    seror:         catris-1999 + (cb2/sigma) grad(mu).grad(nutilde)
!                   (seror et al., j. aircraft 42(1), 2005)
!
!  all terms are treated explicitly (no contribution to qq).
    use blockpointers
    use constants
    use paramturb
    use inputphysics, only : densitycorrsa
    implicit none
! local variables.
    integer(kind=inttype) :: i, j, k, ii
    real(kind=realtype) :: fact, rhox, rhoy, rhoz, nux, nuy, nuz, mux, &
&   muy, muz
    real(kind=realtype) :: gradrhonu, nu, coef, src, cb3inv, divu
    intrinsic mod
    cb3inv = one/rsacb3
!$ad ii-loop
    do ii=0,nx*ny*nz-1
      i = mod(ii, nx) + 2
      j = mod(ii/nx, ny) + 2
      k = ii/(nx*ny) + 2
      fact = half/vol(i, j, k)
      if (densitycorrsa .eq. sadensitycatrisaupoix) then
! original (non-conservative) form of the
! catris-aupoix model, d(rho nutilde)/dt on the left
! hand side: divided by rho this adds nutilde div(u)
! to the equation for nutilde solved here.
        divu = fact*(w(i+1, j, k, ivx)*si(i, j, k, 1)-w(i-1, j, k, ivx)*&
&         si(i-1, j, k, 1)+w(i, j+1, k, ivx)*sj(i, j, k, 1)-w(i, j-1, k&
&         , ivx)*sj(i, j-1, k, 1)+w(i, j, k+1, ivx)*sk(i, j, k, 1)-w(i, &
&         j, k-1, ivx)*sk(i, j, k-1, 1)+w(i+1, j, k, ivy)*si(i, j, k, 2)&
&         -w(i-1, j, k, ivy)*si(i-1, j, k, 2)+w(i, j+1, k, ivy)*sj(i, j&
&         , k, 2)-w(i, j-1, k, ivy)*sj(i, j-1, k, 2)+w(i, j, k+1, ivy)*&
&         sk(i, j, k, 2)-w(i, j, k-1, ivy)*sk(i, j, k-1, 2)+w(i+1, j, k&
&         , ivz)*si(i, j, k, 3)-w(i-1, j, k, ivz)*si(i-1, j, k, 3)+w(i, &
&         j+1, k, ivz)*sj(i, j, k, 3)-w(i, j-1, k, ivz)*sj(i, j-1, k, 3)&
&         +w(i, j, k+1, ivz)*sk(i, j, k, 3)-w(i, j, k-1, ivz)*sk(i, j, k&
&         -1, 3))
        src = w(i, j, k, itu1)*divu
      else
! cell-centred gradients of rho, nutilde and mu
! (green-gauss with the neighbouring cell values,
! see sasource).
        rhox = fact*(w(i+1, j, k, irho)*si(i, j, k, 1)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 1)+w(i, j+1, k, irho)*sj(i, j, k, 1)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 1)+w(i, j, k+1, irho)*sk(i, j, k, 1)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 1))
        rhoy = fact*(w(i+1, j, k, irho)*si(i, j, k, 2)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 2)+w(i, j+1, k, irho)*sj(i, j, k, 2)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 2)+w(i, j, k+1, irho)*sk(i, j, k, 2)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 2))
        rhoz = fact*(w(i+1, j, k, irho)*si(i, j, k, 3)-w(i-1, j, k, irho&
&         )*si(i-1, j, k, 3)+w(i, j+1, k, irho)*sj(i, j, k, 3)-w(i, j-1&
&         , k, irho)*sj(i, j-1, k, 3)+w(i, j, k+1, irho)*sk(i, j, k, 3)-&
&         w(i, j, k-1, irho)*sk(i, j, k-1, 3))
        nux = fact*(w(i+1, j, k, itu1)*si(i, j, k, 1)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 1)+w(i, j+1, k, itu1)*sj(i, j, k, 1)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 1)+w(i, j, k+1, itu1)*sk(i, j, k, 1)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 1))
        nuy = fact*(w(i+1, j, k, itu1)*si(i, j, k, 2)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 2)+w(i, j+1, k, itu1)*sj(i, j, k, 2)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 2)+w(i, j, k+1, itu1)*sk(i, j, k, 2)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 2))
        nuz = fact*(w(i+1, j, k, itu1)*si(i, j, k, 3)-w(i-1, j, k, itu1)&
&         *si(i-1, j, k, 3)+w(i, j+1, k, itu1)*sj(i, j, k, 3)-w(i, j-1, &
&         k, itu1)*sj(i, j-1, k, 3)+w(i, j, k+1, itu1)*sk(i, j, k, 3)-w(&
&         i, j, k-1, itu1)*sk(i, j, k-1, 3))
        gradrhonu = rhox*nux + rhoy*nuy + rhoz*nuz
! (nu + nutilde) grad(rho).grad(nutilde): conservative form
        nu = rlv(i, j, k)/w(i, j, k, irho)
        coef = nu + w(i, j, k, itu1)
! + cb2 nutilde grad(rho).grad(nutilde): catris (1999)
        if (densitycorrsa .eq. sadensitycatris1999 .or. densitycorrsa &
&           .eq. sadensityseror) coef = coef + rsacb2*w(i, j, k, itu1)
        src = coef*gradrhonu
! + cb2 grad(mu).grad(nutilde): seror et al. (2005)
        if (densitycorrsa .eq. sadensityseror) then
          mux = fact*(rlv(i+1, j, k)*si(i, j, k, 1)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 1)+rlv(i, j+1, k)*sj(i, j, k, 1)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 1)+rlv(i, j, k+1)*sk(i, j, k, 1)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 1))
          muy = fact*(rlv(i+1, j, k)*si(i, j, k, 2)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 2)+rlv(i, j+1, k)*sj(i, j, k, 2)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 2)+rlv(i, j, k+1)*sk(i, j, k, 2)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 2))
          muz = fact*(rlv(i+1, j, k)*si(i, j, k, 3)-rlv(i-1, j, k)*si(i-&
&           1, j, k, 3)+rlv(i, j+1, k)*sj(i, j, k, 3)-rlv(i, j-1, k)*sj(&
&           i, j-1, k, 3)+rlv(i, j, k+1)*sk(i, j, k, 3)-rlv(i, j, k-1)*&
&           sk(i, j, k-1, 3))
          src = src + rsacb2*(mux*nux+muy*nuy+muz*nuz)
        end if
! the terms are divided by sigma and rho.
        src = cb3inv*src/w(i, j, k, irho)
      end if
      scratch(i, j, k, idvt) = scratch(i, j, k, idvt) + src
    end do
  end subroutine sadensitycorrectionsource

